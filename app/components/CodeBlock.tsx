type Props = {
  // Syntax-highlighted HTML of the code, pre-rendered by Prism at build time.
  html: string;
};

export default function CodeBlock({ html }: Props) {
  return (
    <pre className="h-full w-full p-2 bg-gray-50 rounded-lg border border-gray-300 whitespace-pre-wrap break-words">
      {/* Trusted HTML generated by Prism when the site was built. */}
      <code dangerouslySetInnerHTML={{ __html: html }} />
    </pre>
  );
}
